// Хранилище уже использованных ID комментариев,
// чтобы исключить повторения.
const usedCommentIds = new Set();

// Создаёт один комментарий.
const createComment = () => {
  let id;

  // Генерируем уникальный ID комментария.
  do {
    id = getRandomInteger(1, 99999);
  } while (usedCommentIds.has(id));

  usedCommentIds.add(id);

  // Формируем текст комментария:
  // выбираем 1–2 случайных сообщения и объединяем их.
  const message = Array.from(
    { length: getRandomInteger(1, 2) },
    () => getRandomArrayItem(COMMENT_MESSAGES)
  ).join(' ');

  return {
    id,
    avatar: `img/avatar-${getRandomInteger(1, 6)}.svg`, // случайный аватар
    message,
    name: getRandomArrayItem(COMMENT_NAMES) // случайное имя автора
  };
};

// Создаёт массив комментариев для одного фото.
// Количество — от 0 до 30.
const createComments = () =>
  Array.from({ length: getRandomInteger(0, 30) }, createComment);

// Создаёт объект одного фото.
const createPhoto = (id) => ({
  id,
  url: `photos/${id}.jpg`, // путь к изображению
  description: DESCRIPTIONS[id - 1], // описание по ID
  likes: getRandomInteger(15, 200), // случайное число лайков
  comments: createComments() // массив комментариев
});

// Создаёт массив из 25 фотографий.
export const createPhotos = () =>
  Array.from({ length: 25 }, (_, i) => createPhoto(i + 1));

